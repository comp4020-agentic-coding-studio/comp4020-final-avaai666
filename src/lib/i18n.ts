export const DICT: Record<Lang, Record<string, string>> = { en, zh };

export const isLang = (s: unknown): s is Lang => s === "en" || s === "zh";

// the lang cookie, from a Cookie header; anything else is English
export function langFrom(cookieHeader: string | undefined): Lang {
  for (const part of (cookieHeader ?? "").split(";")) {
    const eq = part.indexOf("=");
    if (eq > 0 && part.slice(0, eq).trim() === "lang") {
      const v = part.slice(eq + 1).trim();
      return isLang(v) ? v : "en";
    }
  }
  return "en";
}

// t(lang, key, vars): the word, with {var}s filled in. A var given as
// "@key" is itself a word from the dictionary (a round's or a role's name the
// server sent as a code). An unknown language gives English; an unknown key
// gives the key itself (the test keeps both dictionaries complete).
export function t(lang: Lang, key: string, vars: Record<string, string | number> = {}): string {
  const s = (DICT[lang] ?? DICT.en)[key] ?? DICT.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k: string) => {
    if (!(k in vars)) return m;
    const v = String(vars[k]);
    return v.startsWith("@") ? t(lang, v.slice(1)) : v;
  });
}

